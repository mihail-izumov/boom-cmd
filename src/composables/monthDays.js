// Календарь месяца по часовому поясу МОСКВЫ — чистый модуль (нет vue/DOM).
//
// ЗАЧЕМ ОТДЕЛЬНО ОТ ДАННЫХ. Бейдж деки месяца раньше считал остаток дней как
// `daysTotal - daysDone`, где daysDone = число ЗАКРЫТЫХ дней в выгрузке. Это не
// календарь, а состояние источника: пока в payload не приехал вчерашний день,
// бейдж показывал лишний день-два («Осталось 3 дня» 30 июля при реальном
// остатке 2). Остаток месяца — факт календаря, он не может зависеть от того,
// успел ли кто-то закрыть день в таблице.
//
// ПОЧЕМУ МОСКВА, А НЕ ЛОКАЛЬНАЯ ЗОНА УСТРОЙСТВА. Месяц закрывается по бизнесу,
// а бизнес живёт в Москве (парки МСК/СПб — одна зона). Владелец, открывший PWA
// из другого пояса, обязан видеть тот же остаток, что и в парке.
//
// СЕГОДНЯШНИЙ ДЕНЬ ВХОДИТ В ОСТАТОК (решение владельца 30.07.2026): он ещё не
// закрыт, им можно распорядиться — ради этого бейдж и существует. 30 июля →
// «Осталось 2 дня» (30 и 31). Поэтому у текущего месяца остаток никогда не 0.

const MSK = 'Europe/Moscow'

// Один экземпляр форматтера: Intl.DateTimeFormat дорог в конструировании, а
// зона и набор полей у нас постоянные.
const MSK_PARTS = new Intl.DateTimeFormat('en-US', {
  timeZone: MSK,
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
})

// Текущая дата в Москве. Через formatToParts, а не через разбор строки: формат
// строки зависит от локали рантайма, набор частей — нет.
export function mskToday(now = new Date()) {
  const p = {}
  for (const { type, value } of MSK_PARTS.formatToParts(now)) p[type] = value
  const y = Number(p.year)
  const m = Number(p.month)
  const d = Number(p.day)
  if (!(y && m && d)) return null
  return { y, m, d, ym: `${p.year}-${p.month}` }
}

// Длина месяца. Считаем в UTC (день 0 следующего месяца = последний день этого),
// чтобы локальная зона устройства не сдвинула границу.
export function daysInMonth(y, m) {
  return new Date(Date.UTC(y, m, 0)).getUTCDate()
}

// Сколько дней месяца `ym` (формат 'YYYY-MM') ещё осталось на момент `now` по МСК.
//   текущий месяц → длина месяца − сегодняшнее число + 1 (сегодня входит);
//   прошедший     → 0 («Месяц закрыт»);
//   будущий       → месяц целиком (данных за него ещё нет, но врать нечем);
//   мусор на входе → null, вызывающий сам решает, что показать.
export function daysLeftInMonth(ym, now = new Date()) {
  if (typeof ym !== 'string' || !/^\d{4}-\d{2}$/.test(ym)) return null
  const t = mskToday(now)
  if (!t) return null
  if (ym < t.ym) return 0
  if (ym > t.ym) {
    const [y, m] = ym.split('-').map(Number)
    return daysInMonth(y, m)
  }
  return daysInMonth(t.y, t.m) - t.d + 1
}
