import { formatInt } from './analytics.js'

const NBSP = ' '

// «207 249 ₽» — для сообщений валидации сумм.
export function rub(n) {
  return `${formatInt(n)}${NBSP}₽`
}

const MONTH_GEN = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря']

// 'YYYY-MM-DD' → «20 июля» (+ год, если не текущий) — экран успеха, плашка даты.
export function dateHuman(iso, now = new Date()) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso || ''))
  if (!m) return String(iso || '')
  const [, y, mo, d] = m
  const base = `${Number(d)} ${MONTH_GEN[Number(mo) - 1] || mo}`
  return Number(y) === now.getFullYear() ? base : `${base} ${y}`
}

