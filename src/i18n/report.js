// «Безнал + нал = X ₽, а выручка Y ₽. Разница Z ₽ — проверьте цифры» (ТЗ §4).
export function sumMismatch(sum, revenue) {
  const diff = Math.abs(sum - revenue)
  return `Безнал + нал = ${rub(sum)}, а выручка ${rub(revenue)}. Разница ${rub(diff)} — проверьте цифры`
}
