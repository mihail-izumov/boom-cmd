// «Безнал + нал + личный кабинет = X ₽, а выручка Y ₽. Разница Z ₽ —
// проверьте цифры» (ТЗ v2 §2).
export function sumMismatch(sum, revenue) {
  const diff = Math.abs(sum - revenue)
  return `Безнал + нал + личный кабинет = ${rub(sum)}, а выручка ${rub(revenue)}. Разница ${rub(diff)} — проверьте цифры`
}
