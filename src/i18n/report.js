// Форматирование значений плиток. Доли приходят 0..1.
export function summaryValue(key, v) {
  if (v == null || !Number.isFinite(v)) return ''
  if (key === 'avg_check' || key === 'per_topup') return `≈${NBSP}${rub(Math.round(v))}`
  if (key === 'topups_per_session') return v.toFixed(2).replace('.', ',')
  return `${Math.round(v * 100)}${NBSP}%`
}

