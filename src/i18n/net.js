// ПОЧЕМУ НЕ ОДИН ТЕКСТ НА ВСЁ. Совет «выключите VPN» верен только для ТРАНСПОРТНОЙ
// осечки: запрос не дошёл, ответ не пришёл вовремя, вместо JSON прилетела страница.
// Если бэк ответил осознанно (400, 500, протухшая фраза доступа), VPN ни при чём —
// и совет отправит человека крутить настройки впустую, а настоящую причину спрячет.
// Различие уже несёт `netPolicy`: поле `retriable` у ошибки и есть «транспортная».

export const NET_HINTS = {
  offline: 'Нет интернета. Проверьте связь и повторите',
  vpn: 'Похоже, включён VPN — выключите его и нажмите «Повторить»',
}

/** Есть ли связь по мнению браузера. Нет navigator — считаем, что есть (не пугаем зря). */
export function isOnline() {
  try {
    return typeof navigator === 'undefined' || navigator.onLine !== false
  } catch {
    return true
  }
}

/**
 * Что сказать человеку. ЧИСТАЯ функция — вся развилка проверяется без DOM и сети.
 *   офлайн                     → про связь (VPN тут ни при чём);
 *   транспортная осечка онлайн → про VPN (самая частая причина у нас);
 *   отказ бэка                 → '' (подсказки нет, показываем техническую причину).
 * Порядок веток важен: офлайн проверяется ПЕРВЫМ, иначе человек без интернета
 * пойдёт выключать VPN, которого у него может и не быть.
 */
export function networkHint({ retriable = false, online = true } = {}) {
  if (!online) return NET_HINTS.offline
  return retriable ? NET_HINTS.vpn : ''
}
