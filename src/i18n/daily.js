export const DOW_SHORT = ['пн', 'вт', 'ср', 'чт', 'пт', 'сб', 'вс']

// 'YYYY-MM-DD' → «16.05» (DD.MM, без локали).
export function ddmm(iso) {
  const s = String(iso || '')
  if (s.length < 10) return s
  return `${s.slice(8, 10)}.${s.slice(5, 7)}`
}
// Целые рубли с разделителем тысяч: «44 000 ₽».
export function rubWhole(n) {
  if (n == null || !Number.isFinite(Number(n))) return DASH
  return `${formatInt(Math.round(Number(n)))}${NBSP}₽`
}

// ── ДРАЙВЕРЫ РОСТА В «КОНТРОЛЕ ДНЯ» (задание 06.08, §3.1–3.2) ────────────────
// Предложный падеж месяца — только для «Включений в августе не было». Два парка из
// трёх прямо сейчас живут именно в этом случае, поэтому строка обязана читаться
// нормально, а не выглядеть сломанным шаблоном.
const MONTH_PREP = ['январе', 'феврале', 'марте', 'апреле', 'мае', 'июне', 'июле', 'августе', 'сентябре', 'октябре', 'ноябре', 'декабре']
export function monthPrep(ym) {
  const mi = Number(String(ym).split('-')[1])
  return MONTH_PREP[mi - 1] || 'этом месяце'
}

// «DRV-04 с 01.08», «DRV-07 с ~23.07» (точность даты ≠ день).
const evLabel = (e) => `${e.code} с ${e.approx ? '~' : ''}${ddmm(e.iso)}`

// Часть сводки по одному типу событий. Кодов печатаем максимум ДВА: колонка узкая,
// а третий код уже не читается — остаток уходит в «и ещё N» (§3.1).
function evPart(list, one, many) {
  if (!list.length) return ''
  if (list.length === 1) return `${one} ${evLabel(list[0])}`
  const head = list.slice(0, 2).map(evLabel).join(', ')
  const rest = list.length - 2
  return `${many(list.length)}: ${head}${rest > 0 ? ` и ещё ${rest}` : ''}`
}

/**
 * Что переключили в этом месяце — подводка внутри кнопки (§3.1, D-75).
 * Это ЕДИНСТВЕННЫЙ факт «Контроля дня», которого нет в разделе «Драйверы роста»:
 * там видно, что вообще работает, здесь — что изменилось именно в этом месяце.
 * Разделитель « · » интерфейсный; запрет «·» из D-70/D-72 касается текста сводок
 * для мессенджера, а не UI. «выключено 0» не печатается — это шум.
 */
export function driversSwitches(d, ym) {
  if (!d) return ''
  // NET-33: начало периода — это «включён» ИЛИ «перестроен», и печатать их одним
  // глаголом нельзя. Ровно на этом Охта Молл получила «Включён 1: DRV-04 с 01.08»
  // про драйвер, который работает непрерывно с 16.07 и 01.08 был лишь перестроен.
  const on = (d.starts || []).filter((e) => e.kind !== 'rebuilt')
  const re = (d.starts || []).filter((e) => e.kind === 'rebuilt')
  const parts = [
    on.length
      ? evPart(on, 'Включён 1:', (n) => `Включено ${n}`)
      : `Включений в ${monthPrep(ym)} не было`,
  ]
  const reb = evPart(re, 'перестроен', (n) => `перестроено ${n}`)
  if (reb) parts.push(reb)
  const off = evPart(d.ends, 'выключен', (n) => `выключено ${n}`)
  if (off) parts.push(off)
  return parts.join(' · ')
}

/**
 * Подводка внутри кнопки — СИГНАЛ, а не пересказ данных (правка владельца 06.08).
 *
 * Здесь стояло «Включён 1: DRV-04 с 01.08». Владелец назвал это шумом, и он прав:
 * у двух парков из трёх включений в месяце нет вообще, и строка девять раз из десяти
 * сообщала «ничего не произошло». Событие включения и так помечено бейджем «ДР» в
 * дне, а даты живут в разделе.
 *
 * Вместо пересказа — единственный вопрос, на который по этим данным можно ответить
 * честно и который меняет решение: **сможем ли мы вообще узнать, работают драйверы
 * или нет.** Драйвер без замера — это трата смены вслепую, и по сети таких сейчас
 * большинство. Эффект драйвера мы по-прежнему НЕ считаем и не показываем (D-33/D-41):
 * это про готовность измерения, а не про результат.
 */
export function driversMeasureSignal(d) {
  if (!d || !d.total) return ''
  const blind = d.total - d.measuring
  return blind > 0 ? `Без замера ${blind} из ${d.total}` : `Замер идёт у всех ${d.total}`
}

